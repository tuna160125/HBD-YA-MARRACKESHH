let currentSong = 1;
const giftCompletionKey = 'sama-birthday-gift-completion';
let giftCompletion = { bouquet: false, songs: false, birthday: false, plans: false };

try {
  giftCompletion = { ...giftCompletion, ...JSON.parse(localStorage.getItem(giftCompletionKey) || '{}') };
} catch { localStorage.removeItem(giftCompletionKey); }

function allGiftsComplete() { return Object.values(giftCompletion).every(Boolean); }
function updateChatEntry() {
  const entry = document.querySelector('#chat-entry');
  if (!entry) return;
  entry.hidden = !allGiftsComplete();
  if (allGiftsComplete()) window.dispatchEvent(new CustomEvent('sama:gifts-complete'));
}
function completeGift(gift) {
  if (giftCompletion[gift]) return;
  giftCompletion[gift] = true;
  localStorage.setItem(giftCompletionKey, JSON.stringify(giftCompletion));
  updateChatEntry();
}

function openChatShell() {
  const overlay = document.querySelector('#chat-overlay');
  const access = document.querySelector('#chat-access');
  const conversation = document.querySelector('#chat-conversation');
  if (!overlay) return;
  overlay.hidden = false;
  if (access) access.hidden = false;
  if (conversation) conversation.hidden = true;
  document.body.classList.add('chat-is-open');
  window.dispatchEvent(new CustomEvent('sama:open-chat'));
}

function showScreen(id) {
  const next = document.querySelector(`#${id}`);
  const current = document.querySelector('.screen--active');
  if (current === next) return;
  if (current) { current.classList.remove('screen--active'); setTimeout(() => { current.hidden = true; }, 620); }
  next.hidden = false;
  requestAnimationFrame(() => next.classList.add('screen--active'));
  if (id !== 'songs') pauseAudio();
  next.scrollTo({ top: 0, behavior: 'smooth' });
}

function isArabic(text) { return /[\u0600-\u06FF]/.test(text); }
function buildQuotes() {
  quoteCloud.replaceChildren();
  siteContent.bouquet.quotes.forEach((text, index) => {
    const quote = document.createElement('p'); quote.className = 'quote'; quote.textContent = `“${text}”`;
    quote.style.animationDelay = `${.25 + index * .22}s, ${1.3 + index * .18}s`;
    if (isArabic(text)) { quote.lang = 'ar'; quote.dir = 'rtl'; }
    quoteCloud.append(quote);
  });
}
function setAssetImage(img, placeholder, source) {
  img.hidden = true;
  if (placeholder) placeholder.hidden = false;
  img.src = source;
  img.onload = () => { img.hidden = false; if (placeholder) placeholder.hidden = true; };
  img.onerror = () => { img.hidden = true; if (placeholder) placeholder.hidden = false; };
}
function setSong(number) {
  currentSong = number; const song = siteContent.songs[`song${number}`];
  document.querySelector('#song-title').textContent = song.title;
  document.querySelector('#song-subtitle').textContent = song.subtitle;
  setAssetImage(cover, coverPlaceholder, song.cover);
  audio.src = song.audio; audio.load();
  progress.value = 0; updateProgress();
}
function formatTime(seconds) { if (!Number.isFinite(seconds)) return '0:00'; return `${Math.floor(seconds / 60)}:${String(Math.floor(seconds % 60)).padStart(2, '0')}`; }
function updateProgress() { const percent = audio.duration ? (audio.currentTime / audio.duration) * 100 : 0; progress.value = percent; progress.style.setProperty('--progress', `${percent}%`); document.querySelector('#current-time').textContent = formatTime(audio.currentTime); document.querySelector('#duration').textContent = formatTime(audio.duration); }
function setPlayingState(playing) { vinyl.classList.toggle('is-playing', playing); playToggle.classList.toggle('is-paused', playing); playToggle.setAttribute('aria-label', playing ? 'Pause song' : 'Play song'); }
async function playAudio() { try { await audio.play(); tapToBegin.hidden = true; } catch { tapToBegin.hidden = false; } }
function pauseAudio() { audio.pause(); setPlayingState(false); }
function normaliseDate(value) { return value.trim().toLowerCase().replace(/\s+/g, ' '); }
function buildPlanCards() {
  const grid = document.querySelector('#plans-grid');
  grid.replaceChildren();
  siteContent.futurePlans.cards.forEach((plan, index) => {
    const card = document.createElement('button');
    card.type = 'button'; card.className = 'plan-card'; card.setAttribute('aria-pressed', 'false');
    const artwork = plan.images.map(path => `<img src="${path}" alt="">`).join('');
    card.innerHTML = `<span class="plan-card__inner"><span class="plan-card__face plan-card__front"><span>our dream</span><strong>0${index + 1}</strong></span><span class="plan-card__face plan-card__back"><span class="plan-card__artwork">${artwork}</span><strong>${plan.title}</strong><span>${plan.text}</span></span></span>`;
    card.addEventListener('click', () => { const flipped = card.classList.toggle('is-flipped'); card.setAttribute('aria-pressed', String(flipped)); });
    grid.append(card);
  });
}
function buildStoryTimeline() {
  const timeline = document.querySelector('#story-timeline');
  if (!timeline || timeline.childElementCount) return;
  const observer = 'IntersectionObserver' in window ? new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add('is-revealed');
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.16 }) : null;

  siteContent.story.photos.forEach((photo, index) => {
    const item = document.createElement('article');
    item.className = `story-memory story-memory--${photo.position} story-memory--${photo.style}`;
    item.style.setProperty('--memory-turn', `${index % 2 ? 2.2 : -2.2}deg`);
    const frame = document.createElement('div'); frame.className = 'story-memory__frame';
    const image = document.createElement('img');
    image.src = photo.image; image.alt = `Sama growing up — memory ${String(index + 1).padStart(2, '0')}`;
    image.addEventListener('error', () => item.hidden = true);
    frame.append(image);
    const doodle = document.createElement('span'); doodle.className = 'story-memory__doodle'; doodle.setAttribute('aria-hidden', 'true');
    doodle.textContent = ['♡', '✦', '❀', '♡', '✧', '❀', '♡'][index % 7];
    item.append(frame);
    if (photo.caption) {
      const caption = document.createElement('p'); caption.className = 'story-memory__caption'; caption.textContent = photo.caption;
      item.append(caption);
    }
    item.append(doodle);
    timeline.append(item);
    if (index < siteContent.story.photos.length - 1) {
      const connector = document.createElement('div'); connector.className = `story-connector story-connector--${index % 2 ? 'right' : 'left'}`;
      connector.setAttribute('aria-hidden', 'true'); connector.innerHTML = `<span class="story-connector__doodle">${['♡', '✦', '❀', '♡', '✧', '❀'][index % 6]}</span><b>⌁</b><i></i>`;
      timeline.append(connector);
    }
    if (observer) observer.observe(item); else item.classList.add('is-revealed');
  });
}

